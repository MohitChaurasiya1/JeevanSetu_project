import React from 'react';
import RiskIndicator from './RiskIndicator';

const PredictionResultCard = ({ result }) => {
  if (!result) return null;

  const probabilityPercent = result.probability !== undefined && result.probability !== null
    ? (result.probability * 100).toFixed(1)
    : null;

  return (
    <div className="mt-4 p-5 bg-white rounded-xl shadow-card border border-border">
      <div className="flex items-center justify-between pb-3 border-b border-border mb-3">
        <h3 className="text-base font-semibold text-text">Assessment Result</h3>
        {probabilityPercent && (
          <span className="text-xs font-medium text-text-secondary bg-slate-100 px-2.5 py-1 rounded-full">
            Calculated Probability: {probabilityPercent}%
          </span>
        )}
      </div>

      <RiskIndicator prediction={result.prediction} />

      <p className="mt-3 text-xs text-text-muted leading-relaxed text-center">
        This initial assessment is generated by machine learning for informational purposes and does not replace professional medical advice.
      </p>
    </div>
  );
};

export default PredictionResultCard;